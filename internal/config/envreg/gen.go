// HelmProperty is one config.env property in values.schema.json. Its type is
// the same for every key, known or not — any YAML scalar, which the chart
// renders with `quote` (a map or list would render as Go's map syntax).
type HelmProperty struct {
	Type        []string `json:"type"`
	Description string   `json:"description"`
}

// HelmSchema is the generated config.env subtree.
type HelmSchema struct {
	Type                 string                  `json:"type"`
	Description          string                  `json:"description"`
	Properties           map[string]HelmProperty `json:"properties"`
	AdditionalProperties HelmAdditional          `json:"additionalProperties"`
}

// HelmAdditional types the keys config.env accepts beyond the registry's.
type HelmAdditional struct {
	Type []string `json:"type"`
}

// helmValueTypes are the YAML scalars config.env accepts: the chart renders
// each with `quote`, so a number or a bool reaches the pod as its string.
var helmValueTypes = []string{"string", "number", "boolean"}

// helmScoped reports whether an entry belongs in the control-plane pod's
// environment: not the install/update scripts, the test harnesses, or the
// variables the OS / kubelet provide.
func helmScoped(e *Entry) bool {
	if e.Scope == ScopeScripts || e.Scope == ScopeTest || e.Scope == ScopeCLI {
		return false
	}
	return e.Group != GroupPlatform && e.Name != "KUBERNETES_SERVICE_HOST" && e.Name != "KUBERNETES_SERVICE_PORT"
}

// HelmEnvSchema returns the config.env subtree of the chart's values schema.
// Every control-plane setting is a known property (with its description, so
// an editor with schema support shows it); the map stays open
// (additionalProperties) because bundle-declared connector credentials and
// their per-account variants are legitimate config.env keys the registry
// cannot enumerate.
func HelmEnvSchema() HelmSchema {
	s := HelmSchema{
		Type: "object",
		Description: "Extra environment for the control plane, rendered verbatim (quote every value). Properties are generated from " +
			"the configuration registry (docs/CONFIGURATION.md, `make config-docs`); other keys — the client bundle's connector " +
			"variables — are accepted too. Put secrets in config.existingSecret instead.",
		Properties:           map[string]HelmProperty{},
		AdditionalProperties: HelmAdditional{Type: helmValueTypes},
	}
	for _, e := range All() {
		if !helmScoped(&e) {
			continue
		}
		d := e.Description
		if e.Secret {
			d += " Secret: set it through config.existingSecret, not config.env."
		}
		if e.Helm != "" {
			d += " The chart sets it from " + strings.Trim(e.Helm, "()") + "; set that value instead."
		}
		switch {
		case e.DefaultFrom != "":
			d += " Default: inherited from " + e.DefaultFrom + "."
		case e.Default != "":
			d += " Default: " + strings.Trim(e.Default, "()") + "."
		}
		s.Properties[e.Name] = HelmProperty{Type: helmValueTypes, Description: d}
	}
	return s
}

// RewriteHelmSchema replaces the "env" member of the top-level "config"
// object in values.schema.json with the generated subtree, leaving every
// other byte of the hand-written schema untouched.
func RewriteHelmSchema(src []byte) ([]byte, error) {
	cfg := bytes.Index(src, []byte(`"config": {`))
	if cfg < 0 {
		return nil, errors.New(`values.schema.json: no "config" object`)
	}
	rel := bytes.Index(src[cfg:], []byte(`"env": `))
	if rel < 0 {
		return nil, errors.New(`values.schema.json: no "env" member under "config"`)
	}
	start := cfg + rel + len(`"env": `)
	end, err := matchBrace(src, start)
	if err != nil {
		return nil, err
	}
	lineStart := bytes.LastIndexByte(src[:cfg+rel], '\n') + 1
	indent := string(src[lineStart : cfg+rel])

	gen, err := renderHelmEnv(HelmEnvSchema(), indent)
	if err != nil {
		return nil, err
	}

	out := make([]byte, 0, len(src)+len(gen))
	out = append(out, src[:start]...)
	out = append(out, gen...)
	out = append(out, src[end+1:]...)
	if !json.Valid(out) {
		return nil, errors.New("values.schema.json: rewrite produced invalid JSON")
	}
	return out, nil
}

// renderHelmEnv writes s in the schema file's own style: the object spread
// over lines at indent, each property one line (`"NAME": { … }`), sorted.
func renderHelmEnv(s HelmSchema, indent string) ([]byte, error) {
	str := func(v any) (string, error) {
		var b bytes.Buffer
		enc := json.NewEncoder(&b)
		enc.SetEscapeHTML(false)
		if err := enc.Encode(v); err != nil {
			return "", err
		}
		return strings.TrimRight(b.String(), "\n"), nil
	}
	in1, in2 := indent+"  ", indent+"    "
	desc, err := str(s.Description)
	if err != nil {
		return nil, err
	}
	addl, err := str(s.AdditionalProperties)
	if err != nil {
		return nil, err
	}
	names := make([]string, 0, len(s.Properties))
	for n := range s.Properties {
		names = append(names, n)
	}
	sort.Strings(names)
	var b bytes.Buffer
	b.WriteString("{\n")
	fmt.Fprintf(&b, "%s\"type\": %q,\n", in1, s.Type)
	fmt.Fprintf(&b, "%s\"description\": %s,\n", in1, desc)
	fmt.Fprintf(&b, "%s\"properties\": {\n", in1)
	for i, n := range names {
		prop := s.Properties[n]
		d, err := str(prop.Description)
		if err != nil {
			return nil, err
		}
		p := `{ "type": ["` + strings.Join(prop.Type, `", "`) + `"], "description": ` + d + " }"
		sep := ","
		if i == len(names)-1 {
			sep = ""
		}
		fmt.Fprintf(&b, "%s%q: %s%s\n", in2, n, p, sep)
	}
	fmt.Fprintf(&b, "%s},\n", in1)
	addl = strings.ReplaceAll(strings.ReplaceAll(addl, `":`, `": `), `","`, `", "`)
	addl = "{ " + strings.TrimSuffix(strings.TrimPrefix(addl, "{"), "}") + " }"
	fmt.Fprintf(&b, "%s\"additionalProperties\": %s\n", in1, addl)
	fmt.Fprintf(&b, "%s}", indent)
	return b.Bytes(), nil
}

// matchBrace returns the index of the '}' closing the object that opens at
// src[start] (which must be '{'), skipping braces inside strings.
func matchBrace(src []byte, start int) (int, error) {
	if start >= len(src) || src[start] != '{' {
		return 0, errors.New(`values.schema.json: "env" is not an object`)
	}
	depth, inStr, esc := 0, false, false
	for i := start; i < len(src); i++ {
		c := src[i]
		switch {
		case esc:
			esc = false
		case inStr && c == '\\':
			esc = true
		case c == '"':
			inStr = !inStr
		case inStr:
		case c == '{':
			depth++
		case c == '}':
			depth--
			if depth == 0 {
				return i, nil
			}
		}
	}
	return 0, errors.New("values.schema.json: unbalanced braces")
}
