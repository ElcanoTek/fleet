// The two generated artifacts (#2053): docs/CONFIGURATION.md and the
// config.env subtree of deploy/helm/fleet/values.schema.json. Both are
// regenerated with `make config-docs` and drift-checked by
// TestGeneratedFilesAreUpToDate, so neither can disagree with the table.

// Markdown renders docs/CONFIGURATION.md from the registry.
func Markdown() []byte {
	var b bytes.Buffer
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	entries := All()

	w("# Configuration reference\n\n")
	w("<!-- GENERATED by `make config-docs` from internal/config/envreg/table.go. Do not edit by hand: TestGeneratedFilesAreUpToDate fails on drift. -->\n\n")
	w("Every environment variable fleet, its operator CLI, its scripts and its test harnesses read, generated from the one\n")
	w("place each is declared: the configuration registry in [`internal/config/envreg/table.go`](../internal/config/envreg/table.go)\n")
	w("([CONFIG-REGISTRY.md](CONFIG-REGISTRY.md) explains the registry). To add or change a setting, edit its entry there and run\n")
	w("`make config-docs`.\n\n")
	w("Client-specific variables (MCP connector credentials, webhook signing secrets, provider API keys) are not listed: the\n")
	w("client bundle's manifest names them, and fleet admits them at startup ([MCP-BUNDLE-ENV.md](MCP-BUNDLE-ENV.md)).\n\n")

	w("## How values are read\n\n")
	w("- **Precedence.** The process environment wins over the env file; the env file (`FLEET_ENV_FILE`, `/etc/fleet/fleet.env`\n")
	w("  on a provisioned box) wins over the default. One layer of surrounding quotes is stripped.\n")
	w("- **fleet's env-file loader admits only listed names.** When fleet reads the env file itself (`FLEET_ENV_FILE`, and\n")
	w("  every operator CLI verb), a variable marked *process env only* is ignored there. It works when something exports it\n")
	w("  into the process environment: the systemd unit's `EnvironmentFile=` (which exports every line of\n")
	w("  `/etc/fleet/fleet.env`), the Helm chart, or the shell.\n")
	w("- **Typed knobs fail loudly.** A variable marked *validated at boot* that is set but does not parse (or is out of range)\n")
	w("  refuses to boot, and `fleet validate-config` reports it. An unset variable gets its default.\n")
	w("- **Secrets** are marked *secret*: `fleet config explain` always redacts them, and in Kubernetes they belong in\n")
	w("  `config.existingSecret`, not `config.env`.\n")
	w("- **No `CHAT_`/`CUTLASS_` aliases.** The legacy `CHAT_<X>`/`CUTLASS_<X>` spellings of a `FLEET_<X>` setting were removed\n")
	w("  ([ADR-0106](adr/0106-remove-the-chat-cutlass-env-aliases.md)): nothing reads them. When one is set, `fleet serve` logs a\n")
	w("  warning at boot, `fleet doctor` warns, and `fleet config explain` names the `FLEET_` key to use instead. The `CHAT_`/\n")
	w("  `CUTLASS_` names listed below are canonical settings of their own, not aliases.\n")
	w("- **Inherited defaults.** A default shown as *inherited from `X`* is setting `X`'s value, resolved the same way\n")
	w("  (`FLEET_METADATA_MODEL` follows `FLEET_TITLE_MODEL` unless set).\n")
	w("- **Inspect a box** with `fleet config explain [KEY…]`. It reports each setting's *configured* value and its source,\n")
	w("  from the sources it can see: the systemd unit's own environment (on a systemd box), your shell, the env file, the\n")
	w("  aliases and the defaults (inherited ones included). It is not the running server's in-memory configuration —\n")
	w("  see [CONFIG-REGISTRY.md](CONFIG-REGISTRY.md).\n\n")

	w("## Sections\n\n")
	for _, g := range Groups {
		w("- [%s](#%s)\n", g, anchor(g))
	}
	w("\n")

	for _, g := range Groups {
		w("## %s\n\n", g)
		w("| Variable | Type | Default | Scope | Description |\n")
		w("| --- | --- | --- | --- | --- |\n")
		for i := range entries {
			e := &entries[i]
			if e.Group != g {
				continue
			}
			w("| `%s` | %s | %s | %s | %s |\n", e.Name, cell(typeLabel(e)), cell(defaultLabel(e)), e.Scope, cell(describe(e)))
		}
		w("\n")
	}

	return b.Bytes()
}

func anchor(heading string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(heading) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '-':
			b.WriteRune(r)
		case r == ' ':
			b.WriteRune('-')
		}
	}
	return b.String()
}

func cell(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "|", `\|`), "\n", " ")
}

func typeLabel(e *Entry) string {
	if e.Type == TypeEnum {
		return "enum: " + strings.Join(e.Enum, ", ")
	}
	return string(e.Type)
}

func defaultLabel(e *Entry) string {
	own := "—"
	switch {
	case e.Default == "":
	case strings.HasPrefix(e.Default, "("):
		own = e.Default
	default:
		own = "`" + e.Default + "`"
	}
	if e.DefaultFrom == "" {
		return own
	}
	s := "inherited from `" + e.DefaultFrom + "`"
	if e.DefaultDerive != nil {
		s += " (derived)"
	}
	if e.Default != "" {
		s += "; else " + own
	}
	return s
}

// describe is the description plus the facts the registry records.
func describe(e *Entry) string {
	parts := []string{e.Description}
	if e.Secret {
		parts = append(parts, "**Secret.**")
	}
	if e.ProcessOnly {
		parts = append(parts, "*Process env only* (fleet's env-file loader does not admit it; export it).")
	}
	if e.Knob != nil {
		v := "*Validated at boot*"
		if e.Knob.Lenient {
			v = "*Validated by `fleet validate-config` (advisory only)*"
		}
		if b := bounds(e.Knob); b != "" {
			v += " (" + b + ")"
		}
		parts = append(parts, v+".")
	}
	other := make([]string, 0, len(e.Aliases))
	for _, a := range e.Aliases {
		s := "`" + a.Name + "`"
		if !a.EnvFile {
			s += " (process env only)"
		}
		other = append(other, s)
	}
	if len(other) > 0 {
		parts = append(parts, "Also read as "+strings.Join(other, ", ")+".")
	}
	if e.Helm != "" {
		parts = append(parts, "Helm: "+helmLabel(e.Helm)+".")
	}
	return strings.Join(parts, " ")
}

func helmLabel(h string) string {
	if strings.HasPrefix(h, "(") {
		return "set by the chart " + h
	}
	return "set by the chart from `" + h + "`"
}

func bounds(k *Knob) string {
	f := func(p *float64) string { return fmt.Sprintf("%g", *p) }
	switch {
	case k.Min != nil && k.Max != nil:
		return f(k.Min) + "–" + f(k.Max)
	case k.Min != nil:
		return "≥ " + f(k.Min)
	case k.Max != nil:
		return "≤ " + f(k.Max)
	}
	return ""
}

