#!/usr/bin/env bash
# flag-sync.sh — vendor files from ElcanoTek/flag (the Flag design system) and
# prove they have not drifted. This script is shared verbatim by every Elcano
# repo; change it in all of them at once (bump FLAG_SYNC_VERSION) or not at all.
#
# The lock file (flag.lock at the repo root) records which flag commit the
# vendored files came from and the sha256 of every file:
#
#   flag <commit-sha>                       flag commit the files were copied from
#   dir  <repo-dir>                         every file under this dir must be locked
#   file <sha256> <flag-path> <repo-path>   one vendored file
#
# <flag-path> is relative to flag's design-system/ directory; <repo-path> is
# relative to the repo root. Blank lines and lines starting with # are ignored.
#
# Commands:
#   check                      offline drift gate (CI): every locked file exists
#                              with its locked hash, and no unlocked file sits in
#                              a locked dir. Never edit vendored files by hand.
#   sync   [FLAG_DIR]          re-copy every locked file from a flag checkout
#                              (default: $FLAG_DIR, else ../flag) and rewrite the
#                              lock with that checkout's commit. A locked `dir`
#                              mirrors its flag directory: new upstream files are
#                              added and files flag removed are deleted.
#   add    [FLAG_DIR] SRC DEST copy flag file or directory SRC to repo path DEST
#                              and lock it (a directory also becomes a `dir`).
#   status [FLAG_DIR]          report locked files that differ from the flag
#                              checkout, and files flag added to a locked `dir`
#                              (exit 3 when the vendor copy is stale).
set -euo pipefail

FLAG_SYNC_VERSION=5
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOCK="$ROOT/flag.lock"

die() { echo "flag-sync: $*" >&2; exit 2; }

sha() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | cut -d' ' -f1
  else shasum -a 256 "$1" | cut -d' ' -f1; fi
}

flag_dir() {
  local d="${1:-${FLAG_DIR:-$ROOT/../flag}}"
  [ -d "$d/design-system" ] || die "no flag checkout at $d (clone ElcanoTek/flag there or pass its path)"
  (cd "$d" && pwd)
}

# clean_flag DIR: refuse a source the lock could not reproduce — not a git
# checkout, or design-system/ has uncommitted or untracked changes.
clean_flag() {
  git -C "$1" rev-parse --verify -q HEAD >/dev/null 2>&1 || die "$1 is not a git checkout of ElcanoTek/flag; the lock must name a real commit"
  [ -z "$(git -C "$1" status --porcelain --untracked-files=all -- design-system)" ] || die "$1 has uncommitted changes under design-system/; commit or stash them so flag.lock names a commit that reproduces the files"
}

flag_commit() { git -C "$1" rev-parse HEAD; }

# write_lock COMMIT DIRS_FILE FILES_FILE
write_lock() {
  {
    echo "# Vendored from ElcanoTek/flag (design-system/). Generated by scripts/flag-sync.sh v$FLAG_SYNC_VERSION."
    echo "# Do not edit vendored files or this lock by hand: run scripts/flag-sync.sh sync, then commit both."
    echo "flag $1"
    sort -u "$2" | sed 's/^/dir /'
    sort -k3 "$3" | sed 's/^/file /'
  } > "$LOCK.tmp"
  mv "$LOCK.tmp" "$LOCK"
}

read_lock() { # emits: kind fields...
  [ -f "$LOCK" ] || die "missing $LOCK"
  grep -v -e '^[[:space:]]*#' -e '^[[:space:]]*$' "$LOCK"
}

# has_dest LIST PATH: does LIST ("sha flag-path repo-path" records) lock PATH?
# Exact string comparison, so paths with regex characters ([ ] . *) are safe.
has_dest() { awk -v p="$2" '$3 == p { found = 1 } END { exit !found }' "$1"; }

# dir_prefix REPO_DIR: the flag directory a locked `dir` mirrors, derived from
# any locked file under it (repo path REPO_DIR/rel <-> flag path PREFIX/rel).
dir_prefix() {
  local d="$1" kind a b c rel
  while read -r kind a b c; do
    [ "$kind" = file ] || continue
    case "$c" in "$d"/*) rel="${c#"$d"/}"; [ "${b%"/$rel"}" != "$b" ] && { echo "${b%"/$rel"}"; return; } ;; esac
  done < <(read_lock)
}

cmd_check() {
  local bad=0 kind a b c locked
  # A truncated or emptied lock must not pass: exactly one flag record and at
  # least one file record, or nothing below proves anything.
  [ "$(read_lock | awk '$1 == "flag"' | wc -l)" -eq 1 ] || { echo "flag-sync: flag.lock must have exactly one 'flag <commit>' line" >&2; exit 1; }
  [ "$(read_lock | awk '$1 == "file"' | wc -l)" -ge 1 ] || { echo "flag-sync: flag.lock locks no files" >&2; exit 1; }
  locked="$(mktemp)"; trap 'rm -f "$locked"' RETURN
  while read -r kind a b c; do
    case "$kind" in
      flag) ;;
      dir) ;;
      file)
        echo "$c" >> "$locked"
        if [ ! -f "$ROOT/$c" ]; then echo "MISSING  $c (flag: $b)"; bad=1
        elif [ "$(sha "$ROOT/$c")" != "$a" ]; then echo "DRIFTED  $c (flag: $b) — re-run scripts/flag-sync.sh sync; never hand-edit"; bad=1
        fi ;;
      *) die "bad lock line: $kind $a $b $c" ;;
    esac
  done < <(read_lock)
  while read -r kind a _; do
    [ "$kind" = dir ] || continue
    [ -d "$ROOT/$a" ] || { echo "MISSING  dir $a"; bad=1; continue; }
    while IFS= read -r f; do
      f="${f#"$ROOT"/}"
      grep -qxF "$f" "$locked" || { echo "UNLOCKED $f (inside vendored dir $a — move product files out, or add it from flag)"; bad=1; }
    done < <(find "$ROOT/$a" -type f ! -name '.DS_Store' | sort)
  done < <(read_lock)
  if [ "$bad" -ne 0 ]; then echo "flag-sync: vendored Flag files drifted from flag.lock" >&2; exit 1; fi
  echo "flag-sync: $(grep -c '^file ' "$LOCK") vendored files match flag.lock ($(awk '$1=="flag"{print substr($2,1,12)}' "$LOCK"))"
}

cmd_sync() {
  local fd dirs files kind a b c d prefix f rel
  fd="$(flag_dir "${1:-}")"; clean_flag "$fd"
  dirs="$(mktemp)"; files="$(mktemp)"; trap 'rm -f "$dirs" "$files"' RETURN
  while read -r kind a b c; do
    case "$kind" in
      dir) echo "$a" >> "$dirs" ;;
      file)
        [ -f "$fd/design-system/$b" ] || continue
        mkdir -p "$(dirname "$ROOT/$c")"
        cp "$fd/design-system/$b" "$ROOT/$c"
        echo "$(sha "$ROOT/$c") $b $c" >> "$files" ;;
    esac
  done < <(read_lock)
  # Mirror locked dirs: add files flag added, drop files flag removed.
  while read -r d; do
    prefix="$(dir_prefix "$d")"
    [ -n "$prefix" ] || die "cannot tell which flag directory $d mirrors (no locked file under it)"
    [ -d "$fd/design-system/$prefix" ] || die "flag no longer has design-system/$prefix (locked as dir $d)"
    while IFS= read -r f; do
      rel="${f#"$fd/design-system/$prefix"/}"
      has_dest "$files" "$d/$rel" && continue
      mkdir -p "$(dirname "$ROOT/$d/$rel")"
      cp "$f" "$ROOT/$d/$rel"
      echo "$(sha "$ROOT/$d/$rel") $prefix/$rel $d/$rel" >> "$files"
    done < <(find "$fd/design-system/$prefix" -type f ! -name '.DS_Store' | sort)
    while IFS= read -r f; do
      rel="${f#"$ROOT"/}"
      has_dest "$files" "$rel" || rm -f "$f"
    done < <(find "$ROOT/$d" -type f | sort)
  done < "$dirs"
  # A single locked file flag removed is an error, not a silent drop.
  while read -r kind a b c; do
    [ "$kind" = file ] || continue
    while read -r d; do case "$c" in "$d"/*) continue 2 ;; esac; done < "$dirs"
    has_dest "$files" "$c" || die "flag no longer has design-system/$b (locked as $c); remove that line or pick its replacement"
  done < <(read_lock)
  write_lock "$(flag_commit "$fd")" "$dirs" "$files"
  echo "flag-sync: synced $(wc -l < "$files" | tr -d ' ') files from flag $(flag_commit "$fd" | cut -c1-12)"
}

cmd_add() {
  local fd src dest dirs files kind a b c f rel
  if [ $# -eq 3 ]; then fd="$(flag_dir "$1")"; shift; else fd="$(flag_dir "")"; fi
  clean_flag "$fd"
  [ $# -eq 2 ] || die "usage: flag-sync.sh add [FLAG_DIR] <flag-path> <repo-path>"
  src="${1%/}"; dest="${2%/}"
  dirs="$(mktemp)"; files="$(mktemp)"; trap 'rm -f "$dirs" "$files"' RETURN
  touch "$LOCK"
  while read -r kind a b c; do
    case "$kind" in
      dir) echo "$a" >> "$dirs" ;;
      file) [ "$c" = "$dest" ] || [ "${c#"$dest"/}" != "$c" ] || echo "$a $b $c" >> "$files" ;;
    esac
  done < <(grep -v -e '^[[:space:]]*#' -e '^[[:space:]]*$' "$LOCK" || true)
  if [ -d "$fd/design-system/$src" ]; then
    echo "$dest" >> "$dirs"
    while IFS= read -r f; do
      rel="${f#"$fd/design-system/$src"/}"
      mkdir -p "$(dirname "$ROOT/$dest/$rel")"
      cp "$f" "$ROOT/$dest/$rel"
      echo "$(sha "$ROOT/$dest/$rel") $src/$rel $dest/$rel" >> "$files"
    done < <(find "$fd/design-system/$src" -type f ! -name '.DS_Store' | sort)
  elif [ -f "$fd/design-system/$src" ]; then
    mkdir -p "$(dirname "$ROOT/$dest")"
    cp "$fd/design-system/$src" "$ROOT/$dest"
    echo "$(sha "$ROOT/$dest") $src $dest" >> "$files"
  else
    die "flag has no design-system/$src"
  fi
  write_lock "$(flag_commit "$fd")" "$dirs" "$files"
  echo "flag-sync: locked $src -> $dest"
}

cmd_status() {
  local fd stale=0 kind a b c prefix f rel
  fd="$(flag_dir "${1:-}")"
  while read -r kind a b c; do
    [ "$kind" = file ] || continue
    if [ ! -f "$fd/design-system/$b" ]; then echo "GONE     $b (removed upstream; locked as $c)"; stale=1
    elif [ "$(sha "$fd/design-system/$b")" != "$a" ]; then echo "STALE    $c (flag changed design-system/$b)"; stale=1
    fi
  done < <(read_lock)
  while read -r kind a _; do
    [ "$kind" = dir ] || continue
    prefix="$(dir_prefix "$a")"
    [ -n "$prefix" ] && [ -d "$fd/design-system/$prefix" ] || continue
    while IFS= read -r f; do
      rel="${f#"$fd/design-system/$prefix"/}"
      awk -v f="$prefix/$rel" -v r="$a/$rel" '$1 == "file" && $3 == f && $4 == r { found = 1 } END { exit !found }' "$LOCK" || { echo "NEW      design-system/$prefix/$rel (flag added it to vendored dir $a)"; stale=1; }
    done < <(find "$fd/design-system/$prefix" -type f ! -name '.DS_Store' | sort)
  done < <(read_lock)
  if [ "$stale" -ne 0 ]; then echo "flag-sync: vendored copy is behind flag $(flag_commit "$fd" | cut -c1-12); run scripts/flag-sync.sh sync" >&2; exit 3; fi
  echo "flag-sync: vendored copy matches flag $(flag_commit "$fd" | cut -c1-12)"
}

case "${1:-check}" in
  check) cmd_check ;;
  sync) shift; cmd_sync "$@" ;;
  add) shift; cmd_add "$@" ;;
  status) shift; cmd_status "$@" ;;
  version) echo "$FLAG_SYNC_VERSION" ;;
  -h|--help|help) sed -n '2,30p' "$0" ;;
  *) die "unknown command $1 (check | sync | add | status)" ;;
esac
